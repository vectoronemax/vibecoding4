import copy
import json
from pathlib import Path

import numpy as np
import shapely
from pyproj import Transformer
from shapely import affinity
from shapely.geometry import mapping, shape

_到米 = Transformer.from_crs(4326, 32651, always_xy=True)
_到经纬 = Transformer.from_crs(32651, 4326, always_xy=True)

文件后缀 = ["_地块.geojson", "_街坊.geojson", "_单元边界.geojson", "_成果信息.json", "_说明书.md", "_轨交站点.csv"]


def _米(几何):
    return shapely.transform(几何, lambda xy: np.column_stack(_到米.transform(xy[:, 0], xy[:, 1])))


def _经纬(几何):
    几何 = shapely.transform(几何, lambda xy: np.column_stack(_到经纬.transform(xy[:, 0], xy[:, 1])))
    return shapely.set_precision(几何, 1e-9)


def 读教学单元(目录):
    目录 = Path(目录)
    内容 = {}
    for 后缀 in 文件后缀:
        路径 = next(目录.glob("*" + 后缀))
        文字 = 路径.read_text(encoding="utf-8-sig")
        内容[后缀] = json.loads(文字) if 后缀.endswith((".geojson", ".json")) else 文字
    return 内容


def _写文件(内容, 前缀):
    return {前缀 + 后缀: 内容[后缀] for 后缀 in 文件后缀}


class _地块表:
    def __init__(self, 要素们):
        self.要素们 = 要素们

    def 取(self, 编号, 代码=None):
        命中 = [f for f in self.要素们 if f["properties"]["地块编号"] == 编号
              and (代码 is None or f["properties"]["用地代码"] == 代码)]
        assert len(命中) == 1, (编号, 代码, len(命中))
        return 命中[0]

    def 改(self, 编号, 代码=None, **属性):
        self.取(编号, 代码)["properties"].update(属性)

    def 量算面积(self, 编号):
        return _米(shape(self.取(编号)["geometry"])).area


def _总建筑面积(要素们):
    合计 = 0.0
    for f in 要素们:
        p = f["properties"]
        if p.get("容积率") in (None, ""):
            continue
        g = _米(shape(f["geometry"])) if f.get("geometry") else None
        面积 = g.area if (g is not None and g.is_valid) else float(p["用地面积_m2"])
        合计 += 面积 * float(p["容积率"])
    return 合计


