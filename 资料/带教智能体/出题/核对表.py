# -*- coding: utf-8 -*-
"""
答案键核对表：每条答案键旁边列出「工具算出的值 + 相关地块属性 + 依据」，讲师逐条打勾，全部认可后在 答案键.yaml 签字。
由 打包.py 在核对通过后调用，写到 出题/答案键_核对表.md（内容固定，没有时间戳，重复打包不会产生改动）。
"""
import json
from pathlib import Path

# 每条规则要看哪些地块字段
相关字段 = {
    "Q01": ["用地代码", "容积率", "建筑高度_m"],
    "Q02": ["街坊编号", "用地代码"],
    "Q03": ["用地代码", "用地性质"],
    "Q04": ["用地代码", "用地性质"],
    "Q05": ["用地代码", "混合比例"],
    "Q06": ["用地代码", "混合比例", "用地性质"],
    "Q08": ["用地代码", "建筑高度_m", "备注"],
    "Q09": ["用地代码", "建筑高度_m", "街坊编号"],
    "Q10": ["用地代码", "容积率", "备注"],
    "Q12": ["用地代码", "规划状态", "配套设施"],
    "Q15": ["用地代码", "用地面积_m2", "备注"],
    "Q17": ["用地代码", "规划状态", "绿地率_pct"],
    "Q18": ["用地代码", "用地面积_m2"],
    "Q19": ["用地代码", "用地面积_m2"],
    "Q20": ["用地代码", "用地面积_m2"],
}
学校代码 = ["Rs1", "Rs2", "Rs3", "Rs4", "Rs5", "Rs6"]


def _读(目录, 后缀):
    路径 = next(Path(目录).glob("*" + 后缀))
    return json.loads(路径.read_text(encoding="utf-8-sig"))


def _值(v):
    return "（空）" if v is None or (isinstance(v, str) and not v.strip()) else str(v)


def _地块证据(规则, 对象, 地块们, 街坊们):
    编号们 = 对象.split("&")
    行 = []
    for 编号 in 编号们:
        命中 = [p for p in 地块们 if p.get("地块编号") == 编号]
        for p in 命中:
            字段 = 相关字段.get(规则, ["用地代码"])
            文字 = " · ".join(k + " " + _值(p.get(k)) for k in 字段)
            if 规则 == "Q09":
                街坊 = 街坊们.get(str(p.get("街坊编号")))
                文字 += " · 所在街坊高度分区 " + (_值(街坊.get("高度分区")) if 街坊 else "（街坊表里没有）")
            行.append(编号 + "：" + 文字)
    return 行


def _街坊证据(对象, 地块们, 街坊们):
    编号 = 对象.replace("街坊", "")
    街坊 = 街坊们.get(编号) or {}
    成员 = [p.get("地块编号") + " " + _值(p.get("用地代码")) + " 容积率 " + _值(p.get("容积率"))
          for p in 地块们 if str(p.get("街坊编号")) == 编号]
    return ["街坊 " + 编号 + "（强度区 " + _值(街坊.get("强度区")) + "，高度分区 " + _值(街坊.get("高度分区")) + "）：" + "；".join(成员)]


def _单元证据(规则, 对象, 地块们):
    if 规则 == "Q11":
        计数 = {c: sum(1 for p in 地块们 if c in str(p.get("用地代码") or "").split("/")) for c in 学校代码}
        return ["学校地块：" + " · ".join(c + "×" + str(n) for c, n in 计数.items() if n) + "（Rs5 九年一贯制同时计小学和初中；Rs1 完全中学同时计初中和高中）"]
    if 规则 == "Q13":
        名称 = 对象.split("/", 1)[1] if "/" in 对象 else ""
        写到 = [p.get("地块编号") + " " + _值(p.get("用地代码")) + "「" + _值(p.get("配套设施")) + "」"
              for p in 地块们 if 名称 and 名称 in str(p.get("配套设施") or "")]
        return ["配套设施里写了「" + 名称 + "」的地块：" + ("；".join(写到) or "无")]
    return []


def _一条(f, 规则们, 地块们, 街坊们):
    规则 = 规则们.get(f["规则"], {})
    行 = ["### " + f["编号"] + " · " + f["规则"] + " " + str(规则.get("名称", "")) + " · " + f["对象"] + " · " + f["严重度"],
         "- 工具：实际 " + _值(f.get("实际值")) + " ／ 限值 " + _值(f.get("限值")) + " —— " + f["说明"]]
    if f["对象"].startswith("街坊"):
        证据 = _街坊证据(f["对象"], 地块们, 街坊们)
    elif f["对象"].startswith("单元") or f["对象"].startswith("说明书"):
        证据 = _单元证据(f["规则"], f["对象"], 地块们)
    else:
        证据 = _地块证据(f["规则"], f["对象"], 地块们, 街坊们)
    行 += ["- 地块：" + x for x in 证据]
    行 += ["- 依据：" + str(规则.get("依据", "")), "- [ ] 认可", ""]
    return 行


def _条目键(段落, 标题, 工具行):
    import re
    return (段落, re.sub(r"^### F\d+ · ", "", 标题), 工具行)


def _勾选表(文字):
    """{(单元, 标题去掉编号, 工具行): 是否已勾}"""
    结果, 段落, 标题, 工具行 = {}, "", "", ""
    for 行 in 文字.splitlines():
        if 行.startswith("## "):
            段落 = 行
        elif 行.startswith("### "):
            标题, 工具行 = 行, ""
        elif 行.startswith("- 工具："):
            工具行 = 行
        elif 行.startswith("- [") and 标题:
            结果[_条目键(段落, 标题, 工具行)] = 行.lower().startswith("- [x]")
    return 结果


def 保留勾选(旧文字, 新文字):
    """重新生成时，内容没变的条目保留讲师已经打的勾；内容变了的条目要重新核对。"""
    旧 = _勾选表(旧文字)
    输出, 段落, 标题, 工具行 = [], "", "", ""
    for 行 in 新文字.splitlines():
        if 行.startswith("## "):
            段落 = 行
        elif 行.startswith("### "):
            标题, 工具行 = 行, ""
        elif 行.startswith("- 工具："):
            工具行 = 行
        elif 行 == "- [ ] 认可" and 旧.get(_条目键(段落, 标题, 工具行)):
            行 = "- [x] 认可"
        输出.append(行)
    return "\n".join(输出) + "\n"


def 生成(实际, 数据目录, 规则库, 答案):
    """实际：{单元: 参考实现的 findings.json 内容}；数据目录：{单元: 成果目录}。返回 Markdown 文字。"""
    规则们 = {r["id"]: r for r in 规则库["规则"]}
    行 = ["# 答案键核对表",
          "",
          "> 由 `打包.py` 自动生成，不要手改。答案键：`出题/答案键.yaml`（" + str(答案.get("版本")) + "，状态：" + str(答案.get("状态")) + "）；"
          "规则库：" + str(规则库.get("版本")) + "。",
          "> 用法：逐条看「工具」和「地块」两行，对照依据判断是不是真的错，认可就把 `[ ]` 改成 `[x]`。"
          "全部认可后，在 `出题/答案键.yaml` 签上审定人、把状态改成「已核对」。",
          "> 有异议：改口径（`资料/质检智能体/规则库_参考.yaml`）或改数据，再重新打包——不要只改答案键去迁就。",
          ""]
    for 单元 in ("教学单元", "变体单元"):
        结果 = 实际[单元]
        地块们 = [f["properties"] for f in _读(数据目录[单元], "_地块.geojson")["features"]]
        街坊们 = {str(f["properties"]["街坊编号"]): f["properties"] for f in _读(数据目录[单元], "_街坊.geojson")["features"]}
        关键 = [f for f in 结果["findings"] if f["严重度"] in ("错误", "待确认")]
        分布 = {}
        for f in 关键:
            分布[f["规则"]] = 分布.get(f["规则"], 0) + 1
        行 += ["## " + 单元 + "（" + str(len(关键)) + " 条）", "",
              "按规则：" + " · ".join(k + " " + str(n) for k, n in 分布.items()), ""]
        for f in 关键:
            行 += _一条(f, 规则们, 地块们, 街坊们)
        其余 = [f for f in 结果["findings"] if f["严重度"] in ("提示", "无法检查")]
        if 其余:
            行 += ["### 不算进答案键（知道就行）", ""]
            行 += ["- " + f["编号"] + " " + f["规则"] + " · " + f["对象"] + " · " + f["严重度"] + " —— " + f["说明"] for f in 其余]
            行 += [""]
    return "\n".join(行).rstrip() + "\n"
