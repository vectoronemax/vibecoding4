def _公共空间(地块们, 人口=1.5, 地区类型="建成区（以城市更新为主）"):
    m = 迷你成果().单元(0, -300, 1000, 1000)   # 单元 100 公顷
    m.信息["规划人口_万人"] = 人口
    m.信息["地区类型"] = 地区类型
    if 人口 is None:
        del m.信息["规划人口_万人"]
    for 编号, 代码, 宽, 高 in 地块们:
        m.加(编号, 代码, 宽=宽, 高=高, 容积率=None, 建筑高度_m=None, 规划状态="新建")
    return m


