"""
生成 L2 用的小样本：每条规则一份 Qxx.json，放进学员包的 带教/小样本/。

每份 = 若干「迷你成果」+ 期望（哪个对象该报什么）：
  违规例  必须报出
  合规例  不能报
  缺值例  报「无法检查」（报「错误」也算对；不能当没事）
口径有分歧的边界值（比如正好 100 米）不放进小样本：那是学员在 L1 自己拍板的，L4 再看口径差异。

坐标：在 EPSG:32651 下按米摆矩形，再转回经纬度写进 geojson。
"""
import copy

from pyproj import Transformer

_到米 = Transformer.from_crs(4326, 32651, always_xy=True)
_到经纬 = Transformer.from_crs(32651, 4326, always_xy=True)
X0, Y0 = _到米.transform(121.45, 31.30)

基本信息 = {
    "单元名称": "小样本（虚构）",
    "编制类型": "整单元控规（小样本）",
    "区位": "主城区·内环外",
    "功能区域": "居住社区",
    "地区类型": "建成区（以城市更新为主）",
    "规划人口_万人": 3.6,
    "坐标系": "WGS-84（EPSG:4326）；量算请转 EPSG:32651",
}


def _经纬(x, y):
    lon, lat = _到经纬.transform(X0 + x, Y0 + y)
    return [round(lon, 9), round(lat, 9)]


def 环(点们):
    点们 = list(点们)
    if 点们[0] != 点们[-1]:
        点们.append(点们[0])
    return {"type": "Polygon", "coordinates": [[_经纬(x, y) for x, y in 点们]]}


def 矩形几何(x, y, 宽, 高):
    return 环([(x, y), (x + 宽, y), (x + 宽, y + 高), (x, y + 高)])


def 蝴蝶几何(x, y, 宽, 高):
    """自相交的「8」字形：几何无效。"""
    return 环([(x, y), (x + 宽, y + 高), (x + 宽, y), (x, y + 高)])


class 迷你成果:
    """按米摆地块；街坊、单元边界默认按地块外包自动生成。"""

    def __init__(self, 前缀="小样本"):
        self.前缀 = 前缀
        self.地块们 = []          # (feature, (x0, y0, x1, y1))
        self.街坊属性 = {}
        self.街坊几何 = {}
        self.单元框 = None
        self.信息 = copy.deepcopy(基本信息)
        self.站点们 = []
        self.说明书 = "# 小样本说明书\n\n这是小样本，没有需要比对的数字。\n"
        self.声明 = None
        self._游标 = 0.0

    def 加(self, 编号, 代码="Rr2", 宽=100.0, 高=100.0, x=None, y=0.0, 街坊=None, 几何=None, **属性):
        if x is None:
            x = self._游标
        self._游标 = max(self._游标, x + 宽 + 20)
        if 街坊 is None:
            街坊 = 编号[:2] if 编号 else "01"
        p = {"地块编号": 编号, "街坊编号": 街坊, "用地代码": 代码, "用地性质": "", "混合比例": "",
             "用地面积_m2": round(宽 * 高), "容积率": 1.5, "建筑高度_m": 24.0, "建筑密度_pct": 28.0,
             "绿地率_pct": 30.0, "规划状态": "保留", "配套设施": "", "备注": ""}
        p.update(属性)
        if 几何 == "空":
            g = None
        elif 几何 == "蝴蝶":
            g = 蝴蝶几何(x, y, 宽, 高)
        else:
            g = 矩形几何(x, y, 宽, 高)
        self.地块们.append(({"type": "Feature", "properties": p, "geometry": g}, (x, y, x + 宽, y + 高)))
        self.街坊属性.setdefault(街坊, {"强度区": "III级", "高度分区": "三级"})
        return self

    def 街坊(self, 编号, **属性):
        self.街坊属性.setdefault(编号, {"强度区": "III级", "高度分区": "三级"}).update(属性)
        return self

    def 站点(self, 名称, 状态, x, y):
        self.站点们.append((名称, 状态, x, y))
        return self

    def 单元(self, x, y, 宽, 高):
        self.单元框 = (x, y, x + 宽, y + 高)
        return self

    def 文件(self):
        框们 = {}
        for 要素, 框 in self.地块们:
            编号 = 要素["properties"]["街坊编号"]
            if 编号 not in self.街坊属性:
                continue
            旧 = 框们.get(编号)
            框们[编号] = 框 if 旧 is None else (min(旧[0], 框[0]), min(旧[1], 框[1]), max(旧[2], 框[2]), max(旧[3], 框[3]))
        街坊要素 = []
        for 编号 in sorted(self.街坊属性):
            if 编号 not in 框们:
                continue
            x0, y0, x1, y1 = 框们[编号]
            属性 = {"街坊编号": 编号}
            属性.update(self.街坊属性[编号])
            街坊要素.append({"type": "Feature", "properties": 属性,
                          "geometry": 矩形几何(x0 - 5, y0 - 5, x1 - x0 + 10, y1 - y0 + 10)})
        if self.单元框:
            ux0, uy0, ux1, uy1 = self.单元框
        else:
            全部 = list(框们.values()) or [(0, 0, 100, 100)]
            ux0 = min(b[0] for b in 全部) - 30
            uy0 = min(b[1] for b in 全部) - 30
            ux1 = max(b[2] for b in 全部) + 30
            uy1 = max(b[3] for b in 全部) + 30
        单元 = {"type": "FeatureCollection", "features": [{"type": "Feature", "properties": {"单元名称": self.信息.get("单元名称")},
                                                         "geometry": 矩形几何(ux0, uy0, ux1 - ux0, uy1 - uy0)}]}
        站点行 = ["名称,状态,lon,lat,来源"]
        for 名称, 状态, x, y in self.站点们:
            lon, lat = _经纬(x, y)
            站点行.append(",".join([名称, 状态, str(lon), str(lat), "小样本"]))
        前 = self.前缀
        文件 = {
            前 + "_地块.geojson": {"type": "FeatureCollection", "features": [f for f, _ in self.地块们]},
            前 + "_街坊.geojson": {"type": "FeatureCollection", "features": 街坊要素},
            前 + "_单元边界.geojson": 单元,
            前 + "_成果信息.json": self.信息,
            前 + "_说明书.md": self.说明书,
            前 + "_轨交站点.csv": "\n".join(站点行) + "\n",
        }
        if self.声明 is not None:
            文件["claims.json"] = self.声明
        return 文件


def 数据集(名称, 成果, 期望, 改阈值=False):
    return {"名称": 名称, "文件": 成果.文件(), "期望": 期望, "改阈值": 改阈值}


