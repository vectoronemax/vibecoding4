from qc_tools import (问题, 无法检查, 不适用, 取参数, 空, 地块对象, 街坊对象, 成对对象,
                      代码前缀命中)


# ↓ 示例：Q18「用地面积与几何面积一致」。照着这个样子写你自己的 5 条。
#   （规则库里要有 Q18 并写上 参数: {相对误差上限_pct: 1}，这个函数才会被用到。）
def check_area_consistency(数据, rule):
    上限 = 取参数(rule, "相对误差上限_pct")          # 规则库里写 1，就是 1%
    for p in 数据.地块:
        对象 = 地块对象(p)
        if not p["_有效"]:
            yield 无法检查(rule, 对象, "几何无效或为空，先修几何")
            continue
        if 空(p.get("用地面积_m2")):
            yield 无法检查(rule, 对象, "用地面积_m2 为空")
            continue
        属性面积 = float(p["用地面积_m2"])
        差 = (p["_面积"] - 属性面积) / 属性面积 * 100
        if abs(差) > 上限:
            yield 问题(rule, 对象, "错误", 实际值=round(p["_面积"]), 限值="属性面积 ±" + str(上限) + "%",
                     说明="量算面积和属性面积相差 " + format(差, "+.1f") + "%")


