#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""L0 岗位说明书 · 验收：qc_agent/岗位说明书.md 有「输入」「输出」「不做」「严重度」四节。"""
import sys

sys.dont_write_bytecode = True

import common as c

v = c.验收("L0")
v.前置()
文件 = c.作品目录 / "岗位说明书.md"
if not 文件.is_file():
    v.坏("没有 qc_agent/岗位说明书.md")
    v.结束()
文字 = c.读文本(文件)
节们 = {"输入": ("输入",), "输出": ("输出",), "不做": ("不做", "不能做", "不许做", "绝对不"), "严重度": ("严重度",)}
for 名, 关键词 in 节们.items():
    内容 = c.节文字(文字, *关键词)
    if 内容 is None:
        v.坏("缺「" + 名 + "」这一节（用 ## 标题）")
    elif len(内容.strip()) < 6:
        v.坏("「" + 名 + "」这一节是空的")
    else:
        v.好("有「" + 名 + "」一节")
不做 = c.节文字(文字, *节们["不做"]) or ""
if 不做:
    条数 = c.列表项数(不做)
    if 条数 < 3:
        v.坏("「不做」只列了 " + str(条数) + " 条，至少 3 条（用 - 开头一条一行）")
    else:
        v.好("「不做」列了 " + str(条数) + " 条")
严重度 = c.节文字(文字, "严重度") or ""
if 严重度:
    缺 = [k for k in ("错误", "提示", "待确认") if k not in 严重度]
    if 缺:
        v.坏("严重度里没有区分：" + "、".join(缺))
    else:
        v.好("严重度区分了 错误 / 提示 / 待确认")
v.结束()
